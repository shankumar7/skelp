// Generates game/data/players.json from scripts/players.txt
const fs = require('fs');
const path = require('path');
const slug = (n) => n.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const rows = fs.readFileSync(path.join(__dirname, 'players.txt'), 'utf8').split('\n').filter((l) => l.trim() && !l.startsWith('#'));
const players = rows.map((l, i) => {
  const [name, role, country, base, rating] = l.split('|');
  return { id: i + 1, key: slug(name), name, role, country, overseas: country !== 'IND', base: +base, rating: +rating };
});
fs.writeFileSync(path.join(__dirname, '..', 'game', 'data', 'players.json'), JSON.stringify(players, null, 0).replace(/},/g, '},\n') + '\n');
console.log(players.length, 'players');

// Also (re)generate the static require() map for the bundled photos in assets/players
const imgDir = path.join(__dirname, '..', 'assets', 'players');
const have = new Set(fs.existsSync(imgDir) ? fs.readdirSync(imgDir).filter((f) => f.endsWith('.jpg')).map((f) => f.slice(0, -4)) : []);
const lines = players.filter((p) => have.has(p.key)).map((p) => `  "${p.key}": require("../assets/players/${p.key}.jpg"),`);
fs.writeFileSync(path.join(__dirname, '..', 'game', 'playerImages.ts'),
  `// Generated by scripts/build-players.js — do not edit by hand.\nexport const PLAYER_IMAGES: Record<string, any> = {\n${lines.join('\n')}\n};\n`);
console.log(lines.length, 'player photos');
